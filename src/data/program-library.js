/** Претвара дан плана у ставке програма (формат repo.saveProgram) */
export function dayToItems(day, exMap) {
  return day.items.map((x) => {
    const ex = exMap.get(x.id);
    const isTime = x.sec != null || ex?.type === 'time';
    const set = isTime
      ? { reps: null, weightKg: null, durationSec: x.sec ?? 60, tempo: null, restSec: x.rest }
      : { reps: x.reps, weightKg: null, durationSec: null, tempo: x.tempo || null, restSec: x.rest };
    return { exerciseId: x.id, note: x.note || '', sets: Array.from({ length: x.sets }, () => ({ ...set })) };
  });
}

/** Напомена програма: циљ, учесталост и прогресија плана */
export function planNote(plan, day) {
  return `${plan.name} · ${day.name}. Циљ: ${plan.goal} Учесталост: ${plan.days}. Прогресија: ${plan.progression}`;
}
